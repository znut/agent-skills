/**
 * board-snapshot — renders a GitHub ProjectV2 board to a local markdown file.
 *
 * Generic port of an internal board-snapshot script with all git machinery
 * removed (no clone, no commit, no push, no change-detection-for-commit — a
 * project can instead derive this file straight into its own working tree
 * via a different mechanism if it wants it committed). This tool only ever
 * WRITES $AGENT_TOOLS_HOME/var/<name>/board-snapshot.md.
 *
 * CLI: `bun tools/board-snapshot/board-snapshot.mjs <configName>` — reads
 * $AGENT_TOOLS_HOME/config/<configName>.json for board identity + token.
 */
import { execFileSync } from "node:child_process"
import { existsSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { pathToFileURL } from "node:url"
import { loadConfig, varDir } from "../lib/config.mjs"
import { expandHome, writeAtomic } from "../lib/fs-util.mjs"

const DAY_MS = 24 * 60 * 60 * 1000
const DEBOUNCE_MS = 60_000
const DONE_RETENTION_MS = 7 * DAY_MS
const STATUS_ORDER = ["Backlog", "Ready", "In Progress", "Done"]
const HEADER = "<!-- DERIVED — DO NOT EDIT. Generated by tools/board-snapshot/board-snapshot.mjs; source of truth = the GitHub board. -->"

function ghJson(args) {
	// env: process.env passed explicitly — Bun's execFileSync does NOT pick up
	// process.env mutations made after process start unless the env option is
	// given (verified empirically); without this, ensureAuth()'s GH_TOKEN
	// assignment below is silently ignored and `gh` falls back to whatever
	// account is logged in via its own stored credentials.
	return JSON.parse(execFileSync("gh", args, { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, env: process.env }))
}

function ensureAuth(config) {
	if (process.env.GH_TOKEN) return
	try {
		process.env.GH_TOKEN = readFileSync(expandHome(config.tokenFile), "utf8").trim()
	} catch {
		console.error(`GH_TOKEN not set and token file unreadable: ${config.tokenFile}`)
		process.exit(1)
	}
}

export function isWithinDebounce(lastRunMs, nowMs, debounceMs = DEBOUNCE_MS) {
	return nowMs - lastRunMs < debounceMs
}

function isDebounced(stateFile) {
	if (!existsSync(stateFile)) return false
	const last = Number(readFileSync(stateFile, "utf8").trim())
	return Number.isFinite(last) && isWithinDebounce(last, Date.now())
}

function recordRun(stateFile) {
	writeAtomic(stateFile, `${Date.now()}\n`)
}

// One targeted paginated query: Status/Service/Tier/Week/Milestone field
// values plus native blockedBy all ride in the same items() page as content —
// no per-item round trip for dependencies (GitHub's GraphQL schema already
// exposes Issue.blockedBy).
function fetchItems(config) {
	const { owner, projectNumber } = config.board
	const items = []
	let cursor = null
	for (;;) {
		const after = cursor ? `, after: "${cursor}"` : ""
		const query = `query { organization(login: "${owner}") { projectV2(number: ${projectNumber}) { items(first: 100${after}) { pageInfo { hasNextPage endCursor } nodes { content { __typename ... on Issue { number title closedAt milestone { title } blockedBy(first: 20) { nodes { number } } } } status: fieldValueByName(name: "Status") { ... on ProjectV2ItemFieldSingleSelectValue { name } } service: fieldValueByName(name: "Service") { ... on ProjectV2ItemFieldSingleSelectValue { name } } tier: fieldValueByName(name: "Tier") { ... on ProjectV2ItemFieldSingleSelectValue { name } } week: fieldValueByName(name: "Week") { ... on ProjectV2ItemFieldIterationValue { title } } } } } } }`
		const res = ghJson(["api", "graphql", "-f", `query=${query}`])
		if (res.errors) throw new Error(`Project items query failed: ${JSON.stringify(res.errors)}`)
		const page = res.data.organization.projectV2.items
		for (const node of page.nodes) {
			if (node.content?.__typename !== "Issue") continue
			items.push({
				number: node.content.number,
				title: node.content.title,
				status: node.status?.name ?? null,
				service: node.service?.name ?? null,
				tier: node.tier?.name ?? null,
				week: node.week?.title ?? null,
				milestone: node.content.milestone?.title ?? null,
				closedAt: node.content.closedAt ?? null,
				blockedBy: node.content.blockedBy.nodes.map((n) => n.number).sort((a, b) => a - b),
			})
		}
		if (!page.pageInfo.hasNextPage) break
		cursor = page.pageInfo.endCursor
	}
	return items
}

export function selectRenderableItems(items, nowMs) {
	const cutoff = nowMs - DONE_RETENTION_MS
	return items.filter((item) => {
		if (item.status !== "Done") return true
		// closedAt is a GitHub API ISO-8601 Zulu instant (never a bare date or
		// locale string) — Date.parse on an unambiguous "Z"-suffixed instant is
		// the identity conversion, not hand-rolled parsing.
		return item.closedAt !== null && Date.parse(item.closedAt) >= cutoff
	})
}

export function sortItems(items) {
	const rank = (status) => {
		const i = STATUS_ORDER.indexOf(status)
		return i === -1 ? STATUS_ORDER.length : i
	}
	return [...items].sort((a, b) => rank(a.status) - rank(b.status) || b.number - a.number)
}

const TIMESTAMP_LINE = /^Generated: .*$/m

export function renderMarkdown(items, generatedAtIso) {
	const lines = [
		HEADER,
		"",
		"# Board snapshot",
		"",
		`Generated: ${generatedAtIso}`,
		"",
		"| # | Title | Status | Service | Tier | Week | Milestone | Blocked-by |",
		"|---|---|---|---|---|---|---|---|",
	]
	for (const item of items) {
		const blockedBy = item.blockedBy?.length ? item.blockedBy.map((n) => `#${n}`).join(", ") : "—"
		lines.push(
			`| #${item.number} | ${item.title.replace(/\|/g, "\\|")} | ${item.status ?? "—"} | ${item.service ?? "—"} | ${item.tier ?? "—"} | ${item.week ?? "—"} | ${item.milestone ?? "—"} | ${blockedBy} |`,
		)
	}
	return `${lines.join("\n").trimEnd()}\n`
}

// generatedAt changes on every run even when board content doesn't — strip it
// before diffing so an unchanged board is detectable as a clean no-op.
export function stripTimestamp(markdown) {
	return markdown.replace(TIMESTAMP_LINE, "Generated: <redacted>")
}

export function run(config) {
	const dir = varDir(config.name)
	const snapshotPath = join(dir, "board-snapshot.md")
	const stateFile = join(dir, ".board-snapshot-last-run")

	if (isDebounced(stateFile)) {
		console.log(`board-snapshot[${config.name}]: debounced (last run < 60s ago), skipping`)
		return
	}
	ensureAuth(config)

	const generatedAt = new Date().toISOString()
	const renderable = selectRenderableItems(fetchItems(config), Date.now())
	const markdown = renderMarkdown(sortItems(renderable), generatedAt)

	writeAtomic(snapshotPath, markdown)
	recordRun(stateFile)
	console.log(`board-snapshot[${config.name}]: wrote ${renderable.length} items`)
}

function main() {
	const name = process.argv[2]
	if (!name) {
		console.error("usage: bun tools/board-snapshot/board-snapshot.mjs <configName>")
		process.exit(1)
	}
	run(loadConfig(name))
}

const isMainModule = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMainModule) main()
